// 返回 { name, time }；不是线索图（网页盘照、地图、底图）返回 null，由调用处用自己的标题
function picCap(id) {
  if (!id) return null;
  if (typeof ITEMS !== "undefined") {
    const it = Object.values(ITEMS).find((x) => x.img === id);
    if (it) return { name: it.title, time: it.time || "" };
  }
  const slash = id.lastIndexOf("/");
  const dir = id.slice(0, slash);
  const name = id.slice(slash + 1);
  const n = PIC_LV.indexOf(dir);
  const lv = PIC_CAP[n];
  const v = lv && lv[name];
  if (!v) return null;
  return Array.isArray(v) ? { name: v[0], time: v[1] } : { name: v, time: lv.time };
}

function picSrc(path) {
  return encodeURI(PIC_ROOT + path + "." + PIC_EXT) + "?v=" + PIC_VER;
}


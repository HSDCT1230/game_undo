function lvPic(name) {
  const n = (typeof S !== "undefined" && S.level) || 1;
  const have = LV_HAVE[name];
  if (!have || have.includes(n)) return pic(n, name);
  const before = have.filter((k) => k < n);
  if (before.length) return pic(before[before.length - 1], name);
  return n > 1 && have.length ? pic(have[0], name) : "";
}


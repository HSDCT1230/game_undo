const S2HK_WORD_MAP = Object.create(null);
let S2HK_WORD_MAX = 2;
for (let wi = 0; wi < S2HK_WORDS.length; wi++) {
  const wk = S2HK_WORDS[wi][0];
  if (!wk || wk.length < 2) continue;
  S2HK_WORD_MAP[wk] = S2HK_WORDS[wi][1];
  if (wk.length > S2HK_WORD_MAX) S2HK_WORD_MAX = wk.length;
}

function s2hkChar(ch) {
  if (Object.prototype.hasOwnProperty.call(S2HK_FIX, ch)) return S2HK_FIX[ch];
  if (Object.prototype.hasOwnProperty.call(S2HK_MAP, ch)) return S2HK_MAP[ch];
  return ch;
}

function toHkTrad(s) {
  if (s == null || s === "") return "";
  s = String(s);
  const n = s.length;
  let out = "";
  let i = 0;
  while (i < n) {
    let hit = null;
    let hitLen = 0;
    const lim = Math.min(S2HK_WORD_MAX, n - i);
    for (let L = lim; L >= 2; L--) {
      const w = s.substr(i, L);
      if (S2HK_WORD_MAP[w] !== undefined) { hit = S2HK_WORD_MAP[w]; hitLen = L; break; }
    }
    if (hit !== null) { out += hit; i += hitLen; continue; }
    out += s2hkChar(s.charAt(i));
    i += 1;
  }
  return out;
}

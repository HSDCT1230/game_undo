/* 第一场这三样不是一进门就全摆在桌上。执照挂在座位正对面，人一坐下就看见；
   讲到「阿乐」那一节，目光才落到桌下的抽屉；再讲到「身边有谁」，才溜到旁边那台没关的电脑。
   一次给三样，等于让人在开头就把这间房看完，中间那一小时就没有新东西了。
   第二场起三样早已看过，不再藏。 */
function clinicReveal(visit) {
  if (visit !== 1) return 3;
  const seg = (S.clinic && S.clinic.seg) || 0;
  return Math.min(seg + 1, 3);
}

function clinicActions(visit) {
  const box = el("div", { class: "scene-actions fork hub-acts" });
  if (visit === 4) {
    const ok = !!S.clinicLooked.drawer4;
    box.append(forkChoice("坐", "scene-act" + (ok ? " primary" : ""), () => {
      if (!ok) {
        showModal("坐低", "抽屉……我想先看一眼。", "", null, () => drawClinic());
        return;
      }
      clinic4Talk();
    }, "坐下来讲"));
    if (!ok) box.append(el("p", { class: "hub-hint" }, ["抽屉。节拍器还在不在"]));
    return box;
  }
  const seg = S.clinic.seg;
  // 只有抽屉是硬门：节拍器是第 12 关「再看一次」和第 14 关「不见了」的落差所在。
  // 执照与电脑一角不挡——看不看都能讲下去，代价是簿子上少一条、后来那句对不上（见 clinicArrival）。
  const hasDrawer = !!(S.clinicLooked && S.clinicLooked.drawer);
  box.append(
    el("p", { class: "clinic-seg" }, ["讲到：" + CLINIC1_SEGS.slice(0, seg).join(" → ") + (seg ? " → " : "") + (CLINIC1_SEGS[seg] || "")]),
    forkChoice("讲", "scene-act primary", clinicSpeak, seg === 0 ? "开始讲" : "继续讲（" + CLINIC1_SEGS[seg] + "）")
  );
  if (seg === 3 && !hasDrawer) box.append(el("p", { class: "hub-hint" }, ["抽屉。缝里那点铜色，我还没看"]));
  return box;
}


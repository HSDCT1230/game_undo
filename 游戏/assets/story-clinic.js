// 两分钟压成 24 秒：钟在走，水管偶尔响一声，中途可以放弃（放弃不算做完，可以再来）。
let watchTimer = 0;

function watchLine(passed) {
  if (passed < 4) return "你坐在厅里，看着钟。";
  if (passed < 12) return "一分钟。屋里很静。";
  if (passed < 20) return "一分半。水龙头响了一声，又停了。";
  if (passed < 24) return "快两分钟了。";
  return "两分钟。";
}

// 传进来的可能是 S.wait（截止时间在 w.watch.until），也可能是 w.watch 本身，两种都认。
function watchTotal(w) {
  const t = Number((w && w.watch && w.watch.total) || (w && w.total));
  return Number.isFinite(t) && t > 0 ? t : 24;
}

function watchLeft(w) {
  const raw = (w && w.watch && w.watch.until) || (w && w.until);
  const until = Number(raw);
  // 拿不到截止时间就当已经到点：宁可立刻结束，也不能让玩家卡在一张走不动的卡上。
  if (!Number.isFinite(until)) return 0;
  return Math.max(0, Math.ceil((until - Date.now()) / 1000));
}

// 已经过去多少秒，永远落在 0..total 之间。
function watchPassed(w) {
  const total = watchTotal(w);
  const left = watchLeft(w);
  const p = total - left;
  if (!Number.isFinite(p)) return total;
  return Math.max(0, Math.min(total, p));
}

function drawWatchCard(w) {
  clearStage();
  // 这张「盯两分钟」的示意图本身是一张很暗的旧图（中间平均亮度只有 22），
  // 0.68 压下去等于黑屏；改用同一间屋、同一机位的夜里厅母图，夜里该有的样子不用再压。
  const { desk, go } = captionShell(pic(7, "场景-夜里后座厅"), 1.12);
  desk.append(el("div", { class: "caption-text" }, [
    el("p", { class: "caption-line" }, [watchLine(watchPassed(w))]),
    el("p", { class: "caption-next" }, ["钟在你对面走。"]),
    el("div", { class: "caption-acts" }, [
      go("不等了", () => { if (w.skip) w.skip(); }),
    ]),
  ]));
  stage.append(desk);
  renderPlaybar();
  watchResume();
}

function watchResume() {
  clearTimeout(watchTimer);
  watchTimer = 0;
  if (!S.wait || !S.wait.watch) return;
  watchTimer = setTimeout(watchTick, 400);
}

function watchTick() {
  const w = S.wait;
  if (!w || !w.watch) return;
  const left = watchLeft(w);
  const passed = watchPassed(w);
  if (left <= 0 || passed >= watchTotal(w)) return watchFinish();
  // 23:12 → 23:13 →（到点）23:14，钟面只走这两格，不给它算出 NaN 的机会
  const mm = 12 + Math.min(2, Math.max(0, Math.floor(passed / 12)));
  setTime("2014年8月20日 周三 23:" + String(mm).padStart(2, "0"));
  // 水管响两声：按「跨过第 8 / 18 秒」判，不靠恰好踩中某一帧
  const mark = passed >= 18 ? 18 : passed >= 8 ? 8 : 0;
  if (mark && mark > (w.drip || 0)) {
    w.drip = mark;
    sfx("drip");
  }
  const node = stage && stage.querySelector(".caption-line");
  if (node) node.textContent = watchLine(passed);
  watchTimer = setTimeout(watchTick, 400);
}

function watchFinish() {
  clearTimeout(watchTimer);
  watchTimer = 0;
  const w = S.wait;
  S.wait = null;
  setTime("2014年8月20日 周三 23:14");
  if (w && w.go) w.go();
}

